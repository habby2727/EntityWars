import { expect, test } from "bun:test";
import { Database } from "bun:sqlite";
import { createServer } from "node:net";
import { mkdtempSync, readdirSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

test("Dungeon deadlines survive restart and abandoned runs cannot be resumed", async () => {
  const port = await new Promise<number>(done => { const socket = createServer().listen(0, "127.0.0.1", () => { const p = (socket.address() as { port: number }).port; socket.close(() => done(p)); }); });
  const dir = mkdtempSync(join(tmpdir(), "ew-dungeon-expiry-")), path = join(dir, "db.sqlite"), db = new Database(path);
  const migrations = resolve(import.meta.dir, "../../migrations/sqlite");
  for (const file of readdirSync(migrations).filter(f => f.endsWith(".sql")).sort()) db.exec(readFileSync(join(migrations, file), "utf8"));
  const env = { ...process.env, DB_PATH: path, NODE_ENV: "development", BUN_ENV: "development", HOST: "127.0.0.1", PORT: String(port), DATABASE_URL: "postgres://x:x@127.0.0.1:1/test", REDIS_URL: "redis://127.0.0.1:1", PG_CONNECT_TIMEOUT_SECONDS: "1", DEBUG_BYPASS: "0", WORLD_SECRET: "dev_world_secret" };
  const spawn = () => Bun.spawn([process.execPath, "src/index.ts"], { cwd: resolve(import.meta.dir, "../.."), env, stdout: "ignore", stderr: "ignore" });
  let server = spawn();
  const request = async (route: string, body?: unknown, token?: string) => { const response = await fetch(`http://127.0.0.1:${port}${route}`, { method: body === undefined ? "GET" : "POST", headers: { "content-type": "application/json", ...(token ? { authorization: `Bearer ${token}` } : {}) }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) }); return { status: response.status, data: await response.json() as any }; };
  const ready = async () => { for (let i = 0; i < 100; i++) { try { if ((await request("/health")).status === 200) return; } catch {} await Bun.sleep(100); } throw new Error("Server not ready"); };
  try {
    await ready();
    let player = (await request("/auth/dev_login", { name: "expiry_test" })).data;
    const initialState = JSON.parse((db.query("SELECT state_json FROM players WHERE player_id=?").get(player.player_id) as any).state_json);
    initialState.lab.hqLevel = 4; initialState.lab.buildings.sync_nexus = { level: 1 };
    db.query("UPDATE players SET state_json=? WHERE player_id=?").run(JSON.stringify(initialState), player.player_id);
    const initial = await request("/dungeon/start", { client_action_id: "initial" }, player.token);
    expect(initial.status).toBe(200);
    const first = await request("/dungeon/start", { client_action_id: "first" }, player.token);
    expect(first.status).toBe(200);
    expect(first.data.run_id).not.toBe(initial.data.run_id);
    expect((db.query("SELECT status FROM dungeon_runs WHERE run_id=?").get(initial.data.run_id) as any).status).toBe("ABANDONED");
    expect(first.data.spell_progress).toEqual(initialState.spell_progress);
    const countBeforeReplay = (db.query("SELECT COUNT(*) AS n FROM dungeon_runs WHERE player_id=?").get(player.player_id) as any).n;
    const replay = await request("/dungeon/start", { client_action_id: "first" }, player.token);
    expect(replay.status).toBe(200);
    expect(replay.data).toEqual(first.data);
    expect((db.query("SELECT COUNT(*) AS n FROM dungeon_runs WHERE player_id=?").get(player.player_id) as any).n).toBe(countBeforeReplay);
    expect((db.query("SELECT COUNT(*) AS n FROM dungeon_runs WHERE player_id=? AND status='ACTIVE'").get(player.player_id) as any).n).toBe(1);
    const loadout = {run_id:first.data.run_id,client_action_id:"loadout",entity_id:"sulfur_01",weapon_ids:[null,null],homunculus_id:null,spell_ids:["cinder_fist","furnace_rush","ash_temper","brimstone_crash"],mode:"attack"};
    const initialized = await request("/dungeon/loadout", loadout, player.token);
    expect(initialized.status).toBe(200);
    expect(initialized.data.combat_state).toBeDefined();
    const replayedLoadout = await request("/dungeon/loadout", loadout, player.token);
    expect(replayedLoadout.status).toBe(200);
    expect(replayedLoadout.data).toEqual(initialized.data);
    const combat = JSON.parse((db.query("SELECT combat_state_json FROM dungeon_runs WHERE run_id=?").get(first.data.run_id) as any).combat_state_json);
    combat.npc.hp = 1; combat.player.hp = combat.player.max_hp = 10000; combat.player.tempo = 1000;
    combat.spells.find((spell: any) => spell.id === "cinder_fist").accuracy = 1;
    db.query("UPDATE dungeon_runs SET combat_state_json=? WHERE run_id=?").run(JSON.stringify(combat), first.data.run_id);
    const winningAction = {run_id:first.data.run_id,client_action_id:"floor-win",expected_revision:1,decision:{turn:1,spell_id:"cinder_fist"}};
    const win = await request("/dungeon/turn", winningAction, player.token);
    expect(win.status).toBe(200); expect(win.data.cleared_floor).toBe(1);
    const replayedWin = await request("/dungeon/turn", winningAction, player.token);
    expect(replayedWin.status).toBe(200);
    expect(replayedWin.data).toEqual(win.data);
    const beforeAbandon = (await request(`/dungeon/leaderboard?month=${first.data.season}`, undefined, player.token)).data.player;
    expect(beforeAbandon.cleared_floor).toBe(1);
    const playerAfterWin = (db.query("SELECT state_json FROM players WHERE player_id=?").get(player.player_id) as any).state_json;
    const heartbeat = await request("/dungeon/heartbeat", {run_id:first.data.run_id}, player.token);
    expect(heartbeat.status).toBe(200);
    expect(heartbeat.data.expires_at - Date.now()).toBeGreaterThan(18000);
    const hidden = await request(`/dungeon/session?run_id=${first.data.run_id}`, undefined, player.token);
    expect(hidden.data.session.status).toBe("ACTIVE");
    expect(hidden.data.session.combat_state).toBeUndefined();
    expect(hidden.data.session.loadout).toBeUndefined();
    expect((await request("/dungeon/session", undefined, player.token)).data.session).toBeNull();
    await Bun.sleep(21000);
    server.kill(); await server.exited; server = spawn(); await ready();
    player = (await request("/auth/dev_login", { name: "expiry_test" })).data;
    expect((await request("/dungeon/heartbeat", {run_id:first.data.run_id}, player.token)).status).toBe(409);
    expect((db.query("SELECT status FROM dungeon_runs WHERE run_id=?").get(first.data.run_id) as any).status).toBe("EXPIRED");
    expect((await request(`/dungeon/leaderboard?month=${first.data.season}`, undefined, player.token)).data.player.cleared_floor).toBe(1);
    expect((await request("/dungeon/turn", winningAction, player.token)).status).toBe(409);
    expect((await request("/dungeon/loadout", loadout, player.token)).status).toBe(409);
    expect((await request("/dungeon/start", {client_action_id:"first"}, player.token)).status).toBe(409);
    const second = await request("/dungeon/start", {client_action_id:"second"}, player.token);
    expect(second.status).toBe(200);
    const third = await request("/dungeon/start", {client_action_id:"third"}, player.token);
    expect(third.status).toBe(200);
    expect((db.query("SELECT status FROM dungeon_runs WHERE run_id=?").get(second.data.run_id) as any).status).toBe("ABANDONED");
    expect((await request("/dungeon/heartbeat", {run_id:second.data.run_id}, player.token)).status).toBe(409);
    const abandon = {run_id:third.data.run_id,client_action_id:"abandon"};
    expect((await request("/dungeon/abandon", abandon, player.token)).data.status).toBe("ABANDONED");
    expect((await request("/dungeon/heartbeat", {run_id:third.data.run_id}, player.token)).status).toBe(409);
    expect((await request("/dungeon/loadout", {...loadout,run_id:third.data.run_id,client_action_id:"after-abandon"}, player.token)).status).toBe(409);
    expect((db.query("SELECT state_json FROM players WHERE player_id=?").get(player.player_id) as any).state_json).toBe(playerAfterWin);
    if (process.env.DUNGEON_GODOT_EXE) {
      const log = join(dir, "godot.log");
      const before = (db.query("SELECT COUNT(*) AS n FROM dungeon_runs WHERE player_id=?").get(player.player_id) as any).n;
      const game = Bun.spawn([process.env.DUNGEON_GODOT_EXE, "--headless", "--path", resolve(import.meta.dir, "../../.."), "--script", "res://scripts/tests/smoke_dungeon_live.gd", "--log-file", log], { env: { ...process.env, APPDATA:dir, DUNGEON_TEST_ROOT:dir, DUNGEON_TEST_TOKEN:player.token, ENTITYWARS_BACKEND_URL:`http://127.0.0.1:${port}` }, stdout:"ignore", stderr:"ignore" });
      let timeout: ReturnType<typeof setTimeout>;
      const code = await Promise.race([game.exited, new Promise<number>(done => { timeout = setTimeout(() => { game.kill(); done(-1); }, 60000); })]);
      clearTimeout(timeout!);
      const output = readFileSync(log,"utf8");
      expect({code, output}).toMatchObject({code:0});
      expect(output).toContain("PASS Dungeon real entry");
      const rows = db.query("SELECT status FROM dungeon_runs WHERE player_id=? ORDER BY started_at DESC").all(player.player_id) as any[];
      expect(rows.length).toBe(before + 2);
      expect(rows[0].status).toBe("ABANDONED");
      expect(rows[1].status).toBe("ABANDONED");
    }
  } finally {
    server.kill(); await server.exited; db.close();
    for (let i=0;i<10;i++) { try { rmSync(dir, {recursive:true,force:true}); break; } catch { await Bun.sleep(100); } }
  }
}, 120000);
