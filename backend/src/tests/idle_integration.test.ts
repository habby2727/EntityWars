import { test, expect } from "bun:test";
import { Database } from "bun:sqlite";
import { createHash } from "node:crypto";
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import Redis from "ioredis";

test("idle sessions, reconnect, replay and legacy deployment with real Redis", async () => {
	const redisBin = Bun.env.REDIS_TEST_BIN;
	if (!redisBin) throw new Error("Set REDIS_TEST_BIN to an isolated redis-server executable");
	const dir = mkdtempSync(join(tmpdir(), "ew-idle-"));
	const dbPath = join(dir, "test.sqlite");
	const db = new Database(dbPath);
	for (const f of readdirSync(resolve(import.meta.dir, "../../migrations/sqlite")).filter(x => x.endsWith(".sql")).sort()) db.exec(readFileSync(resolve(import.meta.dir, "../../migrations/sqlite", f), "utf8"));
	const port = () => { const s = Bun.serve({ port: 0, hostname: "127.0.0.1", fetch: () => new Response() }); const p = s.port!; s.stop(); return p; };
	const rp = port(), bp = port(), base = `http://127.0.0.1:${bp}`;
	const redisProcess = Bun.spawn([redisBin, "--port", String(rp), "--bind", "127.0.0.1", "--save", "", "--appendonly", "no"], { stdout: "ignore", stderr: "ignore" });
	const redis = new Redis(`redis://127.0.0.1:${rp}`, { lazyConnect: true, retryStrategy: () => null });
	redis.on("error", () => {});
	let server: ReturnType<typeof Bun.spawn> | undefined;
	try {
		for (let n = 0; n < 50; n++) { try { await redis.connect(); break; } catch { await Bun.sleep(50); } }
		const env = { ...process.env, DB_PATH: dbPath, NODE_ENV: "test", BUN_ENV: "test", HOST: "127.0.0.1", PORT: String(bp), SESSION_IDLE_ENABLED: "1", DATABASE_URL: "postgres://x:x@127.0.0.1:1/test", REDIS_URL: `redis://127.0.0.1:${rp}`, AUTH_ACCOUNT_TIMEOUT_MS: "100", LOGIN_RATE_LIMIT_MAX: "100" };
		const start = async (enabled: boolean) => {
			server = Bun.spawn([process.execPath, "src/index.ts"], { cwd: resolve(import.meta.dir, "../.."), env: { ...env, SESSION_IDLE_ENABLED: enabled ? "1" : "0" }, stdout: "ignore", stderr: "ignore" });
			for (let n = 0; n < 100; n++) { try { if ((await fetch(base + "/health")).ok) return; } catch {} await Bun.sleep(50); }
			throw new Error("server did not start");
		};
		await start(true);
		const pairResponse = await fetch(base + "/v1/auth/login", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ name: "pairuser" }) });
		expect(pairResponse.status).toBe(200);
		const pair = await pairResponse.json() as { access_token: string; refresh_token: string };
		const idleKey = (token: string) => `idle:${createHash("sha256").update(token).digest("hex")}`;
		await redis.expire(idleKey(pair.access_token), 30);
		const refresh = (token: string) => fetch(base + "/v1/auth/refresh", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ refresh_token: token }) });
		const refreshed = await refresh(pair.refresh_token);
		expect(refreshed.status).toBe(200);
		const nextPair = await refreshed.json() as { access_token: string; refresh_token: string };
		expect(await redis.ttl(idleKey(nextPair.access_token))).toBeLessThanOrEqual(30);
		await redis.del(idleKey(nextPair.access_token));
		expect((await refresh(nextPair.refresh_token)).status).toBe(409);
		expect((await refresh("invalid")).status).toBe(401);
		const login = await fetch(base + "/auth/register", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ username: "idleuser", password: "secret1" }) });
		expect(login.status).toBe(200);
		const account = await login.json() as { token: string; player_id: string };
		const freshResponse = await fetch(base + "/auth/register", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ username: "freshidle", password: "secret1" }) });
		const fresh = await freshResponse.json() as { token: string };
		await redis.del(idleKey(fresh.token));
		expect((await fetch(base + "/player/state", { headers: { authorization: `Bearer ${fresh.token}` } })).status).toBe(409);
		const headers = { authorization: `Bearer ${account.token}`, "content-type": "application/json", "X-EntityWars-Client-Build": "5504" };
		const key = `idle:${createHash("sha256").update(account.token).digest("hex")}`;
		expect(await redis.ttl(key)).toBeGreaterThan(10790);
		await redis.expire(key, 30);
		expect((await fetch(base + "/player/state", { headers })).status).toBe(200);
		expect((await fetch(base + "/chat/state", { headers })).status).toBe(200);
		expect(await redis.ttl(key)).toBeLessThanOrEqual(30);
		const chat = (body: object, replay = false) => fetch(base + "/chat/send", { method: "POST", headers: { ...headers, ...(replay ? { "X-EntityWars-Replay": "1" } : {}) }, body: JSON.stringify(body) });
		expect((await chat({ text: "hello", client_message_id: "idle-chat-1" })).status).toBe(200);
		expect(await redis.ttl(key)).toBeGreaterThan(10790);
		await redis.expire(key, 30);
		expect((await chat({ text: "hello", client_message_id: "idle-chat-1" })).status).toBe(200);
		expect(await redis.ttl(key)).toBeLessThanOrEqual(30);
		await Bun.sleep(2100);
		expect((await chat({ text: "replay", client_message_id: "idle-chat-2" }, true)).status).toBe(200);
		expect(await redis.ttl(key)).toBeLessThanOrEqual(30);
		const state = JSON.parse((db.query("SELECT state_json FROM players WHERE player_id = ?").get(account.player_id) as any).state_json);
		state.wallet.essence = 1000; state.wallet.core = 100;
		db.query("UPDATE players SET state_json = ? WHERE player_id = ?").run(JSON.stringify(state), account.player_id);
		const action = { action_type: "UPGRADE_BUILDING", client_action_id: "idle-upgrade-1", payload: { building_id: "lab_th" }, client_time_unix_ms: 0 };
		const postAction = () => fetch(base + "/player/action", { method: "POST", headers, body: JSON.stringify(action) });
		expect((await postAction()).status).toBe(200);
		expect(await redis.ttl(key)).toBeGreaterThan(10790);
		await redis.expire(key, 30);
		expect((await postAction()).status).toBe(200);
		expect(await redis.ttl(key)).toBeLessThanOrEqual(30);
		expect((db.query("SELECT COUNT(*) AS n FROM action_log WHERE player_id = ? AND client_action_id = ?").get(account.player_id, action.client_action_id) as any).n).toBe(1);
		const invalid = await fetch(base + "/player/action", { method: "POST", headers, body: JSON.stringify({ ...action, client_action_id: "bad", action_type: "INVALID" }) });
		expect(invalid.status).toBe(400); expect(await redis.ttl(key)).toBeLessThanOrEqual(30);
		await redis.del(key);
		const idle = await fetch(base + "/player/state", { headers });
		expect(idle.status).toBe(409); expect((await idle.json() as any).error).toBe("SESSION_IDLE");
		expect((await postAction()).status).toBe(409);
		expect((await chat({ text: "blocked", client_message_id: "idle-chat-3" })).status).toBe(409);
		expect((await fetch(base + "/auth/reconnect", { method: "POST" })).status).toBe(401);
		expect((await fetch(base + "/auth/reconnect", { method: "POST", headers: { authorization: "Bearer invalid" } })).status).toBe(401);
		const expired = "expired-idle-token";
		await redis.set(`sess:${expired}`, JSON.stringify({ userId: account.player_id, createdAt: 1, expiresAt: 2 }), "EX", 60);
		expect((await fetch(base + "/auth/reconnect", { method: "POST", headers: { authorization: `Bearer ${expired}` } })).status).toBe(401);
		expect((await fetch(base + "/world/state", { headers: { authorization: "Bearer invalid" } })).status).toBe(401);
		const godot = Bun.env.GODOT_BIN || join(process.env.USERPROFILE || "", "Desktop", "Godot_v4.6.exe");
		if (!existsSync(godot)) throw new Error("Set GODOT_BIN to run the required headless reconnect test");
		const child = Bun.spawn([godot, "--headless", "--path", resolve(import.meta.dir, "../../.."), "--script", "res://scripts/tests/smoke_idle_reconnect.gd"], { env: { ...env, APPDATA: dir, LOCALAPPDATA: dir, IDLE_TEST_ROOT: dir, IDLE_TEST_TOKEN: account.token, IDLE_TEST_PLAYER: account.player_id, ENTITYWARS_BACKEND_URL: base }, stdout: "pipe", stderr: "pipe" });
		const exit = await Promise.race([child.exited, Bun.sleep(20000).then(() => { child.kill(); throw new Error("Godot reconnect timed out"); })]);
		const output = await new Response(child.stdout).text() + await new Response(child.stderr).text();
		expect({ exit, output }).toEqual({ exit: 0, output: expect.stringContaining("PASS reconnect from Auth with original identity") });
		await redis.del(key);
		expect((await fetch(base + "/auth/reconnect", { method: "POST", headers })).status).toBe(200);
		const recovered = await (await fetch(base + "/player/state", { headers })).json() as any;
		expect(recovered.updated_player_state.player_id).toBe(account.player_id);
		expect((await postAction()).status).toBe(200);
		expect((db.query("SELECT COUNT(*) AS n FROM action_log WHERE player_id = ? AND client_action_id = ?").get(account.player_id, action.client_action_id) as any).n).toBe(1);
		await redis.del(key);
		server!.kill(); await server!.exited;
		await start(false);
		expect((await fetch(base + "/player/state", { headers })).status).toBe(200);
		const oldSessionResponse = await fetch(base + "/auth/login", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ username: "idleuser", password: "secret1" }) });
		const oldSession = await oldSessionResponse.json() as { token: string };
		const oldPairResponse = await fetch(base + "/v1/auth/login", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ name: "legacyuser" }) });
		const oldPair = await oldPairResponse.json() as { access_token: string; refresh_token: string };
		server!.kill(); await server!.exited;
		await start(true);
		const oldHeaders = { authorization: `Bearer ${oldSession.token}` };
		expect((await fetch(base + "/player/state", { headers: oldHeaders })).status).toBe(200);
		expect((await fetch(base + "/player/state", { headers: { authorization: `Bearer ${oldPair.access_token}` } })).status).toBe(200);
		await redis.del(idleKey(oldSession.token));
		expect((await fetch(base + "/player/state", { headers: oldHeaders })).status).toBe(409);
		const migrated = await refresh(oldPair.refresh_token);
		expect(migrated.status).toBe(200);
		const migratedPair = await migrated.json() as { access_token: string; refresh_token: string };
		await redis.del(idleKey(migratedPair.access_token));
		expect((await refresh(migratedPair.refresh_token)).status).toBe(409);
		await redis.set(key, "1", "EX", 10800);
		expect((await fetch(base + "/player/state", { headers })).status).toBe(200);
		redisProcess.kill(); await redisProcess.exited;
		expect((await fetch(base + "/player/state", { headers })).status).toBe(503);
		expect((await fetch(base + "/auth/reconnect", { method: "POST", headers })).status).toBe(503);
	} finally {
		if (server) { server.kill(); await server.exited; }
		redis.disconnect(); if (redisProcess.exitCode === null) redisProcess.kill(); await redisProcess.exited;
		db.close(); rmSync(dir, { recursive: true, force: true });
	}
}, 30000);
